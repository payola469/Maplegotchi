import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { readInputs } from './validate.mjs';
import { pack, json, digest, budget } from './pack.mjs';
export const root = resolve(fileURLToPath(new URL('../../../', import.meta.url)));
export function build(rootDir = root, output = join(rootDir, 'frontend/src/world-room/generated')) {
  const { frames, manifest } = readInputs(rootDir), pages = [];
  for (const group of [...new Set(frames.map((f) => f.pack))].sort()) pages.push(...pack(frames.filter((f) => f.pack === group), group));
  const evidence = budget(pages);
  // Validate everything before replacing generated output; never mutate source files.
  rmSync(output, { recursive: true, force: true }); mkdirSync(output, { recursive: true });
  for (const page of pages) { writeFileSync(join(output, page.name + '.png'), page.png); writeFileSync(join(output, page.name + '.json'), json(page.metadata)); }
  const assets = Object.fromEntries(manifest.map((m) => [m.id, { geometry_version: m.geometry_version, canvas: m.canvas, parts: m.parts, animations: m.animations ?? {}, footprint: m.footprint ?? null, orientations: m.orientations, catalog_slots: m.catalog_slots ?? [] }]));
  const report = { ...evidence, pages: pages.map((p) => ({ name: p.name, pngSha256: p.sha256, metadataSha256: digest(json(p.metadata)), bytes: p.bytes })), frameCount: frames.length };
  const index = '// Generated by R1A-14; never edit or commit.\n' + pages.map((p, i) => `import page${i} from './${p.name}.png?url';`).join('\n') + '\nexport const atlasPages = [\n' + pages.map((p, i) => `{ url: page${i}, data: ${json(p.metadata).trim()} }`).join(',\n') + '\n];\nexport const artManifest = ' + json(assets).trim() + ';\n';
  report.indexSha256 = digest(index);
  writeFileSync(join(output, 'index.ts'), index);
  writeFileSync(join(output, 'budget.json'), json(report));
  return report;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { console.log(JSON.stringify(build(), null, 2)); } catch (e) { console.error(e.message); process.exitCode = 1; }
}
